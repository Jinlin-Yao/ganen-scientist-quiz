"""Create a small, independent memory-card dataset from the reviewed profiles."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = json.loads((root / 'data/people.json').read_text())
fields = ('name', 'field', 'bio', 'note', 'groups', 'awards', 'quotes', 'references', 'links')
payload = {'updated': source['updated'], 'people': [{k: p[k] for k in fields if k in p} for p in source['people']]}
additions = json.loads((root / 'data/memory-additions.json').read_text())
for person in payload['people']:
    extra = additions.get(person['name'])
    if not extra:
        continue
    person['bio'] = extra['bio']
    person['titles'] = extra['titles']
    person['links'] = person.get('links', []) + extra['links']
    person['references'] = person.get('references', []) + [{'document': 'official', 'location': link['title']} for link in extra['links']]
(root / 'memory-data.js').write_text('// Generated by scripts/build-memory.py; edit data/people.json.\nwindow.MEMORY_DATA=' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f"Built memory profiles: {len(payload['people'])}")
